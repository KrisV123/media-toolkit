from typing import Protocol

from media_toolkit.type import DownloadInfo

from media_toolkit.task_types import TaskState, ProgressState, DownloadState
from media_toolkit.backend.event_bus import EventBus

class TaskSupportBasics(Protocol):
    @property
    def download_info(self) -> DownloadInfo: ...
    @property
    def id(self) -> int: ...
    @property
    def event_bus(self) -> EventBus: ...
    @property
    def status(self) -> TaskState: ...
    @property
    def fail(self) -> Exception | None: ...
    @property
    def title(self) -> str: ...

    def progress(self) -> ProgressState: ...
    def check_fallback(self, pos: int | None) -> list[str] | None: ...


class TaskSupportsCollection(TaskSupportBasics, Protocol):
    @property
    def playlist_ord(self) -> int | None: ...
    @property
    def playlist_items(self) -> list[str | None]: ...

    def current_video_progress(self) -> tuple[ProgressState, DownloadState]: ...
